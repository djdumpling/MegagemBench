"""Actor-masking gradient-zero tests for the GRPO loss seam (§A.6).

TRL's `_compute_loss` applies `mask = completion_mask × tool_mask`
(`grpo_trainer.py:2444`); we feed `actor_mask` into `tool_mask` to zero out
tokens generated by `snapshot_k` / `heuristic` opponents. The static seam
check lives in `tests/test_trl_seam.py`; this file verifies the runtime
invariant on a tiny CPU model.

torch is not a project dependency (training runs inside the Modal image, see
docs/training.md), so collection must succeed without it — hence the
module-level ``importorskip``.
"""

from __future__ import annotations

import pytest

torch = pytest.importorskip("torch")
F = pytest.importorskip("torch.nn.functional")


class _TinyLM(torch.nn.Module):
    def __init__(self, vocab: int = 64, hidden: int = 32):
        super().__init__()
        self.embed = torch.nn.Embedding(vocab, hidden)
        self.head = torch.nn.Linear(hidden, vocab, bias=False)

    def forward(self, ids: torch.Tensor) -> torch.Tensor:
        return self.head(self.embed(ids))


def _per_token_neglogp(logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
    flat = F.cross_entropy(
        logits.reshape(-1, logits.size(-1)),
        targets.reshape(-1),
        reduction="none",
    )
    return flat.reshape(targets.shape)


def _per_token_surrogate(neglogp: torch.Tensor, advantages: torch.Tensor) -> torch.Tensor:
    return neglogp * advantages.unsqueeze(1)


def _fresh_batch(seed: int = 0) -> tuple[torch.Tensor, ...]:
    """Rows 0,3 trainable; rows 1,2 frozen. First 2 tokens are prompt."""
    torch.manual_seed(seed)
    B, T, V = 4, 6, 64
    ids = torch.randint(0, V, (B, T + 1))
    inp, tgt = ids[:, :-1], ids[:, 1:]

    actor_ids = ["trainable", "snapshot_0", "heuristic", "trainable"]
    trainable_per_row = torch.tensor(
        [1.0 if a == "trainable" else 0.0 for a in actor_ids]
    )
    actor_mask = trainable_per_row.unsqueeze(1).expand(-1, T)

    completion_mask = torch.ones(B, T)
    completion_mask[:, :2] = 0.0

    advantages = torch.tensor([+1.0, -1.0, +0.5, -0.5])

    return inp, tgt, actor_mask, completion_mask, advantages, actor_ids


def _grad_snapshot(model: torch.nn.Module) -> dict[str, torch.Tensor]:
    return {n: p.grad.detach().clone() for n, p in model.named_parameters()}


def test_actor_mask_matches_trainable_only_baseline():
    inp, tgt, actor_mask, completion_mask, advantages, actor_ids = _fresh_batch()

    model_full = _TinyLM()
    logits = model_full(inp)
    neglogp = _per_token_neglogp(logits, tgt)
    per_token = _per_token_surrogate(neglogp, advantages)
    mask = completion_mask * actor_mask
    (per_token * mask).sum().backward()
    grads_full = _grad_snapshot(model_full)

    trainable_rows = [i for i, a in enumerate(actor_ids) if a == "trainable"]
    model_subset = _TinyLM()
    model_subset.load_state_dict(model_full.state_dict())
    sub_logits = model_subset(inp[trainable_rows])
    sub_per_token = _per_token_surrogate(
        _per_token_neglogp(sub_logits, tgt[trainable_rows]),
        advantages[trainable_rows],
    )
    (sub_per_token * completion_mask[trainable_rows]).sum().backward()
    grads_subset = _grad_snapshot(model_subset)

    # Empirical float32 round-off from different summation orders is ~1e-7;
    # a leaky mask diverges by O(1). 1e-6 separates the two regimes.
    for name in grads_full:
        assert torch.allclose(
            grads_full[name], grads_subset[name], atol=1e-6, rtol=1e-5
        ), f"{name}: non-trainable rows are leaking gradient through the policy."


def test_actor_mask_actually_changes_gradient():
    """Guards the invariance test from passing trivially with a no-op mask."""
    inp, tgt, actor_mask, completion_mask, advantages, _ = _fresh_batch()

    model_masked = _TinyLM()
    logits = model_masked(inp)
    per_token = _per_token_surrogate(_per_token_neglogp(logits, tgt), advantages)
    (per_token * (completion_mask * actor_mask)).sum().backward()
    grads_masked = _grad_snapshot(model_masked)

    model_unmasked = _TinyLM()
    model_unmasked.load_state_dict(model_masked.state_dict())
    logits_u = model_unmasked(inp)
    per_token_u = _per_token_surrogate(_per_token_neglogp(logits_u, tgt), advantages)
    (per_token_u * completion_mask).sum().backward()
    grads_unmasked = _grad_snapshot(model_unmasked)

    max_diffs = {
        name: (grads_masked[name] - grads_unmasked[name]).abs().max().item()
        for name in grads_masked
    }
    assert any(d > 1e-6 for d in max_diffs.values()), (
        f"Actor masking is a no-op. Max per-param diffs: {max_diffs}"
    )


def test_all_frozen_batch_yields_zero_gradient():
    inp, tgt, _, completion_mask, advantages, _ = _fresh_batch()
    actor_mask = torch.zeros_like(completion_mask)

    model = _TinyLM()
    logits = model(inp)
    per_token = _per_token_surrogate(_per_token_neglogp(logits, tgt), advantages)
    (per_token * (completion_mask * actor_mask)).sum().backward()

    for name, param in model.named_parameters():
        assert param.grad is not None, f"{name} has no .grad"
        assert torch.all(param.grad == 0), (
            f"{name}: non-zero grad with all-frozen actor mask "
            f"(max abs = {param.grad.abs().max().item()})."
        )


def test_completion_mask_alone_zeros_prompt_token_gradient():
    """Exercises the completion_mask factor in isolation (actor_mask=ones)."""
    inp, tgt, _, completion_mask, advantages, _ = _fresh_batch()
    actor_mask = torch.ones_like(completion_mask)

    model_a = _TinyLM()
    logits_a = model_a(inp)
    per_token_a = _per_token_surrogate(_per_token_neglogp(logits_a, tgt), advantages)
    (per_token_a * (completion_mask * actor_mask)).sum().backward()
    grads_a = _grad_snapshot(model_a)

    model_b = _TinyLM()
    model_b.load_state_dict(model_a.state_dict())
    logits_b = model_b(inp)
    per_token_b = _per_token_surrogate(_per_token_neglogp(logits_b, tgt), advantages)
    (per_token_b * completion_mask).sum().backward()
    grads_b = _grad_snapshot(model_b)

    for name in grads_a:
        assert torch.allclose(grads_a[name], grads_b[name], atol=1e-6, rtol=1e-5), (
            f"{name}: completion_mask × actor_mask(=ones) ≠ completion_mask alone."
        )


@pytest.mark.parametrize("seed", [0, 1, 2, 17, 42])
def test_actor_mask_matches_baseline_across_seeds(seed: int):
    inp, tgt, actor_mask, completion_mask, advantages, actor_ids = _fresh_batch(
        seed=seed
    )

    model_full = _TinyLM()
    logits = model_full(inp)
    per_token = _per_token_surrogate(_per_token_neglogp(logits, tgt), advantages)
    (per_token * (completion_mask * actor_mask)).sum().backward()
    grads_full = _grad_snapshot(model_full)

    trainable_rows = [i for i, a in enumerate(actor_ids) if a == "trainable"]
    model_subset = _TinyLM()
    model_subset.load_state_dict(model_full.state_dict())
    sub_logits = model_subset(inp[trainable_rows])
    sub_per_token = _per_token_surrogate(
        _per_token_neglogp(sub_logits, tgt[trainable_rows]),
        advantages[trainable_rows],
    )
    (sub_per_token * completion_mask[trainable_rows]).sum().backward()
    grads_subset = _grad_snapshot(model_subset)

    for name in grads_full:
        assert torch.allclose(
            grads_full[name], grads_subset[name], atol=1e-6, rtol=1e-5
        )
